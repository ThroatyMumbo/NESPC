// a keyboard alone: no X
static const uint8_t keyboard[] = {
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01,
    0x95, 0x08, 0x81, 0x02, 0xC0,
};

static void expect(const char *name, const uint8_t *desc, uint16_t dlen, const uint8_t *r, uint16_t rlen,
                   bool ok, int dx, int dy, int wheel, uint8_t buttons) {
    struct mouse_layout m;
    int x = 0, y = 0, w = 0;
    uint8_t b = 0;
    bool got = mouse_parse(desc, dlen, &m) && mouse_read(&m, r, rlen, &x, &y, &w, &b);
    if (got != ok || (ok && (x != dx || y != dy || w != wheel || b != buttons))) {
        printf("FAIL %s: %d dx %d dy %d wheel %d buttons %u\n", name, got, x, y, w, b);
        fails++;
    }
}

int main(void) {
    expect("plain", plain, sizeof plain, (const uint8_t[]){0x05, 0x03, 0xFE, 0xFF}, 4, true, 3, -2, -1, 5);
    expect("plain, wheel up", plain, sizeof plain, (const uint8_t[]){0x00, 0x00, 0x00, 0x02}, 4, true, 0, 0, 2, 0);
    expect("plain, short", plain, sizeof plain, (const uint8_t[]){0x01, 0x03}, 2, false, 0, 0, 0, 0);
    expect("receiver", receiver, sizeof receiver, (const uint8_t[]){0x02, 0x03, 0x00, 0xFB, 0xCF, 0x12, 0xFF, 0x00},
           8, true, -5, 300, -1, 3);
    expect("receiver, keyboard report", receiver, sizeof receiver, (const uint8_t[]){0x01, 0, 0, 4, 0, 0, 0, 0}, 8,
           false, 0, 0, 0, 0);
    expect("keyboard", keyboard, sizeof keyboard, (const uint8_t[]){0, 0, 0}, 3, false, 0, 0, 0, 0);
    if (fails)
        return 1;
    printf("mouse: all passed\n");
    return 0;
}
